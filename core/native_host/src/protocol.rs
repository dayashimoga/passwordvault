#![deny(unsafe_code)]
#![warn(missing_docs)]

//! Wire protocol definitions and length-prefixed framing for browser Native Messaging.

use serde::{Deserialize, Serialize};
use serde_json::Value;
use std::io::{Read, Write};

/// Maximum message size allowed under Chrome/Edge Native Messaging protocol (1 MiB).
pub const MAX_MESSAGE_SIZE: usize = 1024 * 1024;

/// Error types for Native Messaging host operations.
#[derive(Debug, thiserror::Error)]
pub enum HostError {
    /// IO failure during communication.
    #[error("IO error: {0}")]
    Io(#[from] std::io::Error),
    /// JSON serialization/deserialization error.
    #[error("JSON serialization error: {0}")]
    Json(#[from] serde_json::Error),
    /// Message exceeded maximum size limit.
    #[error("Message exceeded maximum allowable length ({0} > {MAX_MESSAGE_SIZE})")]
    MessageTooLarge(usize),
    /// Unknown or missing request type.
    #[error("Invalid request type: {0}")]
    InvalidRequest(String),
    /// Session authentication failed or expired.
    #[error("Unauthorized session token")]
    Unauthorized,
    /// Vault is currently locked.
    #[error("Vault is locked")]
    VaultLocked,
    /// Cryptographic or domain validation error.
    #[error("Validation failed: {0}")]
    Validation(String),
}

/// Vault status returned to extension.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]
pub enum VaultStatus {
    /// Vault file does not exist.
    NotFound,
    /// Vault exists but is locked.
    Locked,
    /// Vault is unlocked and ready for queries.
    Unlocked,
}

/// Request commands dispatched from browser extension to native host.
#[derive(Debug, Clone, Serialize, Deserialize)]
#[serde(tag = "type")]
pub enum NativeRequest {
    /// Initial challenge-response handshake.
    Handshake {
        /// Nonce generated by client extension.
        client_nonce: String,
        /// Chrome/Firefox extension identifier.
        extension_id: String,
    },
    /// Queries current status of the vault.
    Status {
        /// Active session token.
        session_token: Option<String>,
    },
    /// Unlocks vault with master passphrase.
    Unlock {
        /// Active session token.
        session_token: String,
        /// Master passphrase.
        passphrase: String,
        /// Optional path to vault container file.
        vault_path: Option<String>,
    },
    /// Locks vault and purges secrets from host memory.
    Lock {
        /// Active session token.
        session_token: String,
    },
    /// Queries matching logins for active browser tab URL.
    GetLogins {
        /// Active session token.
        session_token: String,
        /// URL of top-level tab document.
        url: String,
    },
    /// Decrypts and retrieves a single credential for form autofill.
    FillCredential {
        /// Active session token.
        session_token: String,
        /// Item ID to fill.
        item_id: String,
        /// Origin URL to ensure domain match.
        url: String,
    },
    /// Generates a strong password using CSPRNG generator.
    GeneratePassword {
        /// Optional password length (default 20).
        length: Option<usize>,
        /// Include symbols (default true).
        symbols: Option<bool>,
    },
    /// Saves newly captured credentials from browser.
    SaveCredential {
        /// Active session token.
        session_token: String,
        /// Item title.
        title: String,
        /// Username or email.
        username: String,
        /// Password.
        password: String,
        /// Origin URL.
        url: String,
    },
}

/// Public summary of a matching login item (password strictly omitted).
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct LoginSummary {
    /// Item identifier.
    pub id: String,
    /// Title of the credential entry.
    pub title: String,
    /// Username or email if present.
    pub username: Option<String>,
    /// Associated primary URL.
    pub url: Option<String>,
}

/// Response returned from native host to browser extension.
#[derive(Debug, Clone, Serialize, Deserialize)]
#[serde(tag = "type")]
pub enum NativeResponse {
    /// Successful handshake response.
    HandshakeResponse {
        /// Session token authorized for subsequent commands.
        session_token: String,
        /// Current state of local vault.
        vault_status: VaultStatus,
        /// Host version.
        host_version: String,
    },
    /// Current vault state response.
    StatusResponse {
        /// Vault status.
        vault_status: VaultStatus,
        /// Total number of active credentials if unlocked.
        item_count: usize,
    },
    /// Vault unlock response.
    UnlockResponse {
        /// Whether unlock was successful.
        success: bool,
        /// Vault name.
        vault_name: String,
        /// Total active credentials loaded.
        item_count: usize,
    },
    /// Vault lock response.
    LockResponse {
        /// Always true.
        success: bool,
    },
    /// Matching credentials for requested web domain.
    GetLoginsResponse {
        /// List of candidate login summaries.
        logins: Vec<LoginSummary>,
    },
    /// Credential payload for DOM autofill.
    FillCredentialResponse {
        /// Username to inject.
        username: Option<String>,
        /// Password to inject.
        password: Option<String>,
    },
    /// Password generation result.
    GeneratePasswordResponse {
        /// Generated secret.
        password: String,
        /// Shannon entropy score.
        entropy_bits: u32,
        /// Strength category rating.
        rating: String,
    },
    /// Credential save result.
    SaveCredentialResponse {
        /// Whether save committed cleanly.
        success: bool,
        /// Assigned item ID.
        item_id: String,
    },
    /// Structured error response.
    ErrorResponse {
        /// Error message.
        error: String,
        /// Numerical status code.
        code: u32,
    },
}

/// Reads a 4-byte length-prefixed JSON message from a stream.
pub fn read_native_message<R: Read>(reader: &mut R) -> Result<Option<Value>, HostError> {
    let mut len_buf = [0u8; 4];
    match reader.read_exact(&mut len_buf) {
        Ok(()) => {}
        Err(e) if e.kind() == std::io::ErrorKind::UnexpectedEof => return Ok(None),
        Err(e) => return Err(HostError::Io(e)),
    }

    let len = u32::from_ne_bytes(len_buf) as usize;
    if len > MAX_MESSAGE_SIZE {
        return Err(HostError::MessageTooLarge(len));
    }
    if len == 0 {
        return Ok(None);
    }

    let mut msg_buf = vec![0u8; len];
    reader.read_exact(&mut msg_buf)?;

    let val: Value = serde_json::from_slice(&msg_buf)?;
    Ok(Some(val))
}

/// Writes a 4-byte length-prefixed JSON message to a stream.
pub fn write_native_message<W: Write>(writer: &mut W, value: &Value) -> Result<(), HostError> {
    let bytes = serde_json::to_vec(value)?;
    let len = bytes.len();
    if len > MAX_MESSAGE_SIZE {
        return Err(HostError::MessageTooLarge(len));
    }

    let len_bytes = (len as u32).to_ne_bytes();
    writer.write_all(&len_bytes)?;
    writer.write_all(&bytes)?;
    writer.flush()?;
    Ok(())
}

#[cfg(test)]
mod tests {
    use super::*;
    use std::io::Cursor;

    #[test]
    fn test_message_framing_roundtrip() {
        let original = serde_json::json!({
            "type": "Status",
            "session_token": "test-token-123"
        });

        let mut buffer = Vec::new();
        write_native_message(&mut buffer, &original).expect("write failed");

        assert!(buffer.len() > 4);

        let mut cursor = Cursor::new(buffer);
        let read = read_native_message(&mut cursor)
            .expect("read failed")
            .expect("none");

        assert_eq!(read, original);
    }

    #[test]
    fn test_message_too_large_rejection() {
        let mut buffer = Vec::new();
        let oversized = (MAX_MESSAGE_SIZE + 1) as u32;
        buffer.extend_from_slice(&oversized.to_ne_bytes());

        let mut cursor = Cursor::new(buffer);
        let result = read_native_message(&mut cursor);
        assert!(matches!(result, Err(HostError::MessageTooLarge(_))));
    }
}
